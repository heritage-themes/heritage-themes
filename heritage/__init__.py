"""Shared generator for every Heritage Themes family.

A theme family is a top-level folder with a theme.py that defines:

    FAMILY  family name, shown in the plugin description
    BLURB   one sentence for the plugin description
    THEMES  one dict(slug, id, palette) per theme

All colour mappings live in this package, so every family is generated by the same code.
"""
import importlib.util, os

from .scheme import scheme
from .ui import theme

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_families():
    """The theme.py module of every top-level folder that has one, in folder name order."""
    families = []
    for name in sorted(os.listdir(ROOT)):
        path = os.path.join(ROOT, name, "theme.py")
        if not os.path.isfile(path):
            continue
        spec = importlib.util.spec_from_file_location(f"heritage_{name}", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        families.append(module)
    return families


def folder(family):
    """The family's folder name, for example "shuimo"."""
    return os.path.basename(os.path.dirname(family.__file__))


def generate(family):
    """One dict per theme with slug, id, name, scheme (editor scheme XML) and theme (UI theme JSON)."""
    return [dict(slug=t["slug"], id=t["id"], name=t["palette"]["name"],
                 scheme=scheme(t["palette"]), theme=theme(t["palette"], t["slug"])) for t in family.THEMES]
